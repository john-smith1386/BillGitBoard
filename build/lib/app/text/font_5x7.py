SPACE_WIDTH = 3
GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7
LETTER_GAP = 1


def validate_font() -> None:
    expected = set("ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789")
    if set(FONT_5X7) != expected:
        raise RuntimeError("5x7 font is incomplete")
    for character, rows in FONT_5X7.items():
        if len(rows) != GLYPH_HEIGHT or any(len(row) != GLYPH_WIDTH for row in rows):
            raise RuntimeError(f"invalid dimensions for glyph {character}")
        if any(set(row) - {"#", "."} for row in rows):
            raise RuntimeError(f"invalid bitmap value for glyph {character}")


validate_font()
